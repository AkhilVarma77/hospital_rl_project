"""Train and evaluate the demand forecasters on SIMULATED arrival data.

Data  : arrival time series generated by the synthetic generator (src/data), one episode per
        (scenario, seed). Training, validation and test use DISJOINT seed ranges (200000+, 300000+,
        1000+), none of which the RL training uses. Test episodes are therefore unseen simulated
        periods. Limitation: all episodes share the same daily pattern, and the configured surge
        always happens at the same time of day, so this does not test generalisation to a
        different pattern.
Models: moving average (window chosen on validation) and an LSTM (early stopping on validation).
Metrics: MAE and RMSE per target on the test episodes, plus an "oracle" that predicts the TRUE
        arrival rate used by the generator. The oracle is not a usable model; it shows the error
        floor caused by the randomness of arrivals.
"""
from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional, Sequence

import numpy as np
import pandas as pd
import torch

from src.data.synthetic_data_generator import SyntheticDataGenerator
from src.forecasting.demand_forecaster import (
    DemandForecaster, LSTMDemandForecaster, LSTMNet, N_TARGETS, build_features, fit_moving_average,
    make_windows)
from src.utils.logging_utils import CSVLogger
from src.utils.seeding import set_global_seed


@dataclass
class ForecastSettings:
    window: int = 16
    scale: float = 3.0
    hidden_size: int = 32
    epochs: int = 25
    lr: float = 0.002
    batch_size: int = 256
    patience: int = 5
    ma_windows: tuple[int, ...] = (1, 2, 4, 8, 16)
    scenarios: tuple[str, ...] = ("normal", "high_demand", "emergency_surge", "mixed_demand")
    train_seed_start: int = 200_000
    train_episodes_per_scenario: int = 40
    val_seed_start: int = 300_000
    val_episodes_per_scenario: int = 8
    test_seed_start: int = 1000
    test_episodes_per_scenario: int = 20

    @classmethod
    def from_config(cls, cfg: dict[str, Any], overrides: Optional[dict[str, Any]] = None) -> "ForecastSettings":
        values = dict(cfg.get("forecast", {}))
        values.update(overrides or {})
        for key in ("ma_windows", "scenarios"):
            if key in values:
                values[key] = tuple(values[key])
        return cls(**values)


# ------------------------------------------------------------------------------ data
def generate_episode(config: dict[str, Any], scenario: str, seed: int) -> tuple[np.ndarray, np.ndarray, int]:
    """-> (counts [T, 2], true expected counts [T, 2], steps_per_day). Columns: total, emergency."""
    gen = SyntheticDataGenerator(config, scenario, seed)
    data = gen.generate_all()
    ts = data["arrival_timeseries"]
    counts = ts[["total_arrivals", "emergency_arrivals"]].to_numpy(dtype=float)
    lam_em, lam_el = gen._expected_arrivals_per_step(data["events"])
    expected = np.stack([lam_em + lam_el, lam_em], axis=1)
    return counts, expected, 1440 // gen.step_minutes


@dataclass
class Dataset:
    histories: np.ndarray      # [N, window, 2]
    steps: np.ndarray          # [N] index of the step being predicted
    targets: np.ndarray        # [N, 2]
    expected: np.ndarray       # [N, 2] true rates (oracle reference only)
    scenario: np.ndarray       # [N] scenario name


def build_dataset(config: dict[str, Any], scenarios: Sequence[str], seeds: Sequence[int],
                  window: int) -> tuple[Dataset, int]:
    hists, steps, targets, expected, names = [], [], [], [], []
    spd = 96
    for scenario in scenarios:
        for seed in seeds:
            counts, rates, spd = generate_episode(config, scenario, seed)
            hists.append(make_windows(counts, window))
            steps.append(np.arange(len(counts)))
            targets.append(counts)
            expected.append(rates)
            names += [scenario] * len(counts)
    return Dataset(np.concatenate(hists), np.concatenate(steps), np.concatenate(targets),
                   np.concatenate(expected), np.asarray(names)), spd


def _seeds(start: int, n: int) -> list[int]:
    return list(range(start, start + n))


# ---------------------------------------------------------------------------- training
def train_lstm(train: Dataset, val: Dataset, st: ForecastSettings, steps_per_day: int, seed: int = 0,
               log_path: Optional[Path] = None, verbose: bool = False) -> LSTMDemandForecaster:
    set_global_seed(seed)
    torch.set_num_threads(1)
    net = LSTMNet(st.hidden_size)
    opt = torch.optim.Adam(net.parameters(), lr=st.lr)
    x_tr, s_tr = build_features(train.histories, train.steps, st.window, steps_per_day, st.scale)
    y_tr = (train.targets / st.scale).astype(np.float32)
    x_va, s_va = build_features(val.histories, val.steps, st.window, steps_per_day, st.scale)
    y_va = (val.targets / st.scale).astype(np.float32)
    x_tr, s_tr, y_tr = map(torch.as_tensor, (x_tr, s_tr, y_tr))
    x_va, s_va, y_va = map(torch.as_tensor, (x_va, s_va, y_va))
    rng = np.random.default_rng(seed)
    logger = CSVLogger(log_path) if log_path else None

    best, best_state, bad = float("inf"), None, 0
    for epoch in range(1, st.epochs + 1):
        net.train()
        order = rng.permutation(len(y_tr))
        losses = []
        for i in range(0, len(order), st.batch_size):
            b = torch.as_tensor(order[i:i + st.batch_size])
            loss = torch.mean((net(x_tr[b], s_tr[b]) - y_tr[b]) ** 2)
            opt.zero_grad()
            loss.backward()
            opt.step()
            losses.append(loss.item())
        net.eval()
        with torch.no_grad():
            val_loss = float(torch.mean((net(x_va, s_va) - y_va) ** 2))
        if logger:
            logger.log({"epoch": epoch, "train_mse_scaled": float(np.mean(losses)), "val_mse_scaled": val_loss})
        if verbose:
            print(f"epoch {epoch:3d} | train {np.mean(losses):.5f} | val {val_loss:.5f}", flush=True)
        if val_loss < best - 1e-7:
            best, bad = val_loss, 0
            best_state = {k: v.clone() for k, v in net.state_dict().items()}
        else:
            bad += 1
            if bad >= st.patience:
                break
    net.load_state_dict(best_state)
    return LSTMDemandForecaster(net, st.window, steps_per_day, st.scale)


# -------------------------------------------------------------------------- evaluation
def _metrics(pred: np.ndarray, actual: np.ndarray) -> dict[str, float]:
    err = pred - actual
    return {"mae_total": float(np.abs(err[:, 0]).mean()), "rmse_total": float(np.sqrt((err[:, 0] ** 2).mean())),
            "mae_emergency": float(np.abs(err[:, 1]).mean()),
            "rmse_emergency": float(np.sqrt((err[:, 1] ** 2).mean())),
            "mean_actual_total": float(actual[:, 0].mean()), "mean_actual_emergency": float(actual[:, 1].mean()),
            "n_steps": int(len(actual))}


def evaluate_forecasters(forecasters: dict[str, DemandForecaster], test: Dataset) -> pd.DataFrame:
    """One row per (model, scenario) plus a pooled 'all' row. Includes the oracle error floor."""
    preds = {name: fc.predict_batch(test.histories, test.steps) for name, fc in forecasters.items()}
    preds["oracle_true_rate"] = test.expected
    rows = []
    for name, p in preds.items():
        for scenario in list(dict.fromkeys(test.scenario)) + ["all"]:
            sel = np.ones(len(p), bool) if scenario == "all" else test.scenario == scenario
            rows.append({"model": name, "scenario": scenario, **_metrics(p[sel], test.targets[sel])})
    return pd.DataFrame(rows)


def run_forecasting_experiment(config: dict[str, Any], out_dir: str | Path, seed: int = 0,
                               overrides: Optional[dict[str, Any]] = None, verbose: bool = True) -> pd.DataFrame:
    """Build data, tune the moving average, train the LSTM, evaluate on held-out episodes, save all."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    st = ForecastSettings.from_config(config, overrides)
    t0 = time.perf_counter()

    train, spd = build_dataset(config, st.scenarios, _seeds(st.train_seed_start, st.train_episodes_per_scenario), st.window)
    val, _ = build_dataset(config, st.scenarios, _seeds(st.val_seed_start, st.val_episodes_per_scenario), st.window)
    test, _ = build_dataset(config, st.scenarios, _seeds(st.test_seed_start, st.test_episodes_per_scenario), st.window)
    if verbose:
        print(f"samples: train {len(train.targets)}, validation {len(val.targets)}, test {len(test.targets)}", flush=True)

    ma, scores = fit_moving_average(val.histories, val.steps, val.targets, st.ma_windows, spd)
    if verbose:
        print("moving-average validation MAE by window:", {k: round(v, 4) for k, v in scores.items()},
              "-> chosen", ma.window, flush=True)
    lstm = train_lstm(train, val, st, spd, seed=seed, log_path=out / "forecaster_training_log.csv", verbose=verbose)

    ma.save(out / "moving_average.json")
    lstm.save(out / "lstm.pt")
    metrics = evaluate_forecasters({f"moving_average(w={ma.window})": ma, "lstm": lstm}, test)
    metrics.to_csv(out / "forecast_metrics.csv", index=False)
    if verbose:
        print(f"done in {time.perf_counter() - t0:.0f}s", flush=True)
    return metrics
